// Infers language ID from file path
export function inferLanguageFromPath(filePath: string): string {
    const base = path.basename(filePath).toLowerCase();
    const ext = path.extname(filePath).replace(/^\./, '').toLowerCase();
    if (base === 'project.godot') {
        return 'gdscript';
    }
    return EXT_TO_LANG[ext] || '';
}

// Get a readable display name
export function getLanguageDisplayName(lang: string): string {
    const canonical = normalizeLanguage(lang);
    return DISPLAY_NAME[canonical.toLowerCase()] ?? DISPLAY_NAME[lang.toLowerCase()] ?? canonical;
}
